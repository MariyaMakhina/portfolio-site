#!/bin/bash

# Проверяем, есть ли аргумент (комментарий)
if [ -z "$1" ]; then
    echo "❌ Ошибка: укажите комментарий!"
    echo "Пример: ./save.sh 'feat: добавила новый блок'"
    exit 1
fi

# Добавляем все изменения
git add .

# Создаём коммит с переданным комментарием
git commit -m "$1"

# Отправляем в GitHub
echo "🚀 Отправка в GitHub..."
git push origin main

# Отправляем в SourceCraft
echo "🚀 Отправка в SourceCraft..."
git push sourcecraft main

echo "✅ Готово! Изменения сохранены в оба репозитория."


